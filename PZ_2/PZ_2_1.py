# Вариант 15. 
# Дано трехзначное число. 
# Вывести вначале его последнюю цифру (единицы), а затем — его среднюю цифру (десятки).


num = input("Введите трехзначное число: ")

# Добавляю обработку исключений, если ввели не трехзначное число
# Зацикливает пока пользователь не введет нужный формат данных
while type(num) != int:
    try:
        num = int(num)
    except ValueError:
        print("Неправильно ввели!")
        num = input("Введите трехзначное число: ")

# Успешно получили инпут - производим действия
num_ed = num % 10
num_des = (num // 10) % 10
print("Вариант 16. Единицы и десятки", num_ed, num_des)



# Дальше решала для себя разные варианты


