# Дан  прямоугольник,  длины  сторон  которого  равны  натуральным  числам  А  и  В. 
# Составить функцию, которая будет находить на сколько квадратов можно разрезать данный  прямоугольник,
# если  от  него  каждый  раз  отрезать  квадрат  наибольшей площади.

def pryamougolnik(A, B):
    t = 0
    while A > 0 and B > 0:
        if A >= B:
            A -= B
        else:
            B -= A
        t += 1
    return t


A = input("Введите первое число: ")
B = input("Введите второе число: ")

while type(A) != int or type(B) != int:  # обработка исключений 
    try: 
        A, B = int(A), int(B) 
    except ValueError: 
        print("Неправильно ввели!") 
        A, B = input("Введите первое целое число: "), input("Введите второе целое число: ")
 
print("Прямоугольник можно разрезать на такое кол-во квадратов: ", pryamougolnik(A, B))