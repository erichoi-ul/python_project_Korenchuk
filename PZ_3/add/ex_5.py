# Дано два числа. 
# Если их сумма кратна 5, то прибавить 1, иначе вычесть 2.

a = int(input("Введите двухзначное число: "))
print('введенное число: ', a)

if a % 5 == 0:
    a += 1
    print("Число кратно 5, увеличили число на 1, число равно: ", a)
else:
    a -= 2
    print("Число не кратно 5, уменьшили число на 2, число равно: ", a)