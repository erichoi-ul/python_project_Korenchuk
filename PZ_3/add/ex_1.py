# Ввести 2 числа. Если их произведение отрицательно, умножить его на 8, 
# в противном случае увеличить его в 1.5 раза.

a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))

sum = a*b

if sum < 0:
    result = sum * 8
    print("Их произведение отрицательно, умножили на 8, число равно ", result)
else:
    result = sum * 1.5
    print("Их произведение положительно, увеличили в 1.5 раза, число равно", result)