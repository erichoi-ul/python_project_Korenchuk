# Ввести число. Если оно четное, разделить его на 4, если нечетное - умножить на 5

a = int(input("Введите число: "))

if a % 2 == 0:
    result = a / 4
    print("Число чётное, разделили на 4, число равно ", result)
else:
    result = a * 5
    print("Число нечётное, умножили на 5, число равно ", result)
    