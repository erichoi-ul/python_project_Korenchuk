# Ввести двухзначное число. 
# Если сумма цифр числа четная, то увеличить число на 2,
# в противном случае уменьшить на 2

a = int(input("Введите двухзначное число: "))

ed = a % 10
des = (a // 10) % 10

sum = ed + des 
print("Сумма чисел: ", sum)

if sum % 2 == 0:
    sum += 2
    print("Сумма чисел чётная, увеличили число на 2, число равно", sum)
else:
    sum -= 2
    print("Сумма чисел нечётная, уменьшили число на 2, число равно", sum)