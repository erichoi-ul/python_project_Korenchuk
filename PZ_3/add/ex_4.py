# Дано целое число. 
# Если оно является положительным, то прибавить к нему 20, 
# в противном случае вычесть из него 5.

a = int(input("Введите двухзначное число: "))
print('введенное число: ', a)

if a > 0:
    a += 20
    print("Число положительное, увеличили число на 20, число равно: ", a)
else:
    a -= 5
    print("Число отрицательное, уменьшили число на 5, число равно: ", a)