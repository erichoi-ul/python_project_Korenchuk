# Задача: Дан список размера N, состоящий из символов. Привести символы букв 
# из верхнего регистра в нижний. Определить количество букв. 

import random         # Импортируем стандартный модуль для случайных чисел

# 1. ПОДГОТОВКА И ВВОД ДАННЫХ
List_4 = [] # Создаем пустой список для будущих случайных символов
d = int(input('Введи размер массива:   ')) # Запрашиваем размер массива у пользователя

# 2. ГЕНЕРАЦИЯ СЛУЧАЙНЫХ СИМВОЛОВ
t = 0 # Счетчик для цикла
while t < d: 
    # Выбираем случайное число от 45 до 100 и превращаем его в символ по таблице ASCII
    random_symbol = chr(random.randint(45, 100))
    List_4.append(random_symbol) # Добавляем сгенерированный символ в список
    t += 1 # Увеличиваем счетчик, чтобы цикл не стал бесконечным

# 3. ВЫВОД ИСХОДНОГО МАССИВА
print('Исходный массив: ', List_4)

# 4. ПОДСЧЕТ КОЛИЧЕСТВА БУКВ
h = 0 # Переменная для подсчета букв
for i in List_4: # Перебираем каждый символ в списке по очереди
    if i.isalpha(): # Проверяем, является ли текущий символ буквой
        h += 1 # Если это буква, прибавляем к счетчику единицу
 
print('Количество букв:   ', h) 

# 5. ПРЕОБРАЗОВАНИЕ И СМЕНА РЕГИСТРА
# Склеиваем все элементы списка в одну цельную строку
New_String = ''.join(List_4) 

# Метод .lower() переводит все заглавные буквы в строке в нижний регистр (маленькие буквы)
print("Переводим буквы в нижний регистр:   ", New_String.lower())
