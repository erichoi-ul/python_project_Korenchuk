# Дана строка-предложение на русском языке. 
# Подсчитать количество содержащихся в строке знаков препинания. 

sentence = input("Введите предложение: ")

#сделала свою библиотеку знаков
punctuation_marks = '.,!?:;-"—–«»()[]}{…'
k = 0

for char in sentence:
    if char in punctuation_marks:
        k += 1
    else:
        continue  

print('Количество содержащихся в строке знаков препинания: ', k)